function mergeDeep(base, override) {
  return Object.entries(override).reduce((next, [key, value]) => {
    if (value && typeof value === 'object' && !Array.isArray(value)) {
      next[key] = mergeDeep(next[key] && typeof next[key] === 'object' ? next[key] : {}, value);
      return next;
    }
    next[key] = value;
    return next;
  }, { ...base });
}

