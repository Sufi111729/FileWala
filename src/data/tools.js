function imageSeo(slug) {
  const [fileName, imageAlt, imageTitle, imageCaption] = toolImageSeoBySlug[slug] ?? [];
  if (!fileName) return {};
  const preview = `/tool-previews/${fileName}`;
  return {
    preview,
    previewImage: preview,
    imageUrl: absoluteUrl(preview),
    imageAlt,
    imageTitle,
    imageCaption,
  };
}

