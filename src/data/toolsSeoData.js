const makeTool = ({
  id,
  title,
  slug,
  route,
  category,
  mainKeyword,
  keywordVariants,
  primaryKeyword,
  secondaryKeywords,
  longTailKeywords,
  questionKeywords,
  indiaKeywords,
  brandKeywords,
  alternateNames,
  seoTitle,
  metaDescription,
  h1,
  intro,
  shortIntro,
  detailedIntro,
  features,
  howToUse,
  benefits,
  benefitsTitle,
  faqs,
  relatedTools,
  schema,
  includeFaqSchema = true,
  includeCommonFaqs = true,
  exactAlternateNames = false,
  ogDescription,
  twitterDescription,
  imageAlt,
  relatedToolsLimit,
  preserveSeoContent = false,
  priority = 0.8,
}) => {
  const profile = keywordProfiles[slug] ?? {};
  const resolvedPrimary = primaryKeyword ?? mainKeyword;
  const resolvedSecondary = unique([...(secondaryKeywords ?? []), ...(profile.secondaryKeywords ?? []), ...(keywordVariants ?? [])]);
  const resolvedQuestionKeywords = unique([...(questionKeywords ?? []), ...(profile.questionKeywords ?? []), ...defaultQuestionKeywords(resolvedPrimary)]);
  const resolvedIndiaKeywords = unique([...(indiaKeywords ?? []), ...(profile.indiaKeywords ?? []), ...defaultIndiaKeywords(resolvedPrimary)]);
  const resolvedAlternateNames = exactAlternateNames
    ? unique(alternateNames ?? [])
    : unique([...(alternateNames ?? []), ...(profile.alternateNames ?? []), ...defaultAlternateNames(title, resolvedPrimary)]);
  const resolvedBrandKeywords = unique(brandKeywords ?? [
    `FileWalaTool ${resolvedPrimary}`,
    `File Wala Tool ${resolvedPrimary}`,
    `file tool ${resolvedPrimary}`,
    `free file tool ${resolvedPrimary}`,
  ]);
  const canonicalUrl = absoluteUrl(route);
  const faqItems = includeCommonFaqs ? [...faqs, commonPrivacyFaq, mobileFaq] : faqs;
  const resolvedFaqs = unique(faqItems.map((faq) => faq.question))
    .map((question) => faqItems.find((faq) => faq.question === question));

  return {
    id,
    title,
    slug,
    route,
    category,
    primaryKeyword: resolvedPrimary,
    secondaryKeywords: resolvedSecondary,
    longTailKeywords: unique([...(longTailKeywords ?? []), ...(profile.longTailKeywords ?? [])]),
    questionKeywords: resolvedQuestionKeywords,
    indiaKeywords: resolvedIndiaKeywords,
    brandKeywords: resolvedBrandKeywords,
    alternateNames: resolvedAlternateNames,
    seoTitle,
    metaDescription,
    ogDescription,
    twitterDescription,
    imageAlt,
    h1,
    shortIntro: shortIntro ?? intro,
    detailedIntro: detailedIntro ?? intro,
    intro,
    features,
    howToUse,
    benefits: benefits ?? defaultBenefits(title, category),
    benefitsTitle,
    faqs: resolvedFaqs,
    relatedTools,
    relatedToolsLimit,
    preserveSeoContent,
    canonicalUrl,
    schema: schema ?? {
      type: 'SoftwareApplication',
      applicationCategory: 'UtilitiesApplication',
    },
    includeFaqSchema,
    schemaType: 'SoftwareApplication',
    priority,
    mainKeyword: resolvedPrimary,
    keywordVariants: unique([
      ...resolvedSecondary,
      ...(longTailKeywords ?? []),
      ...(profile.longTailKeywords ?? []),
      ...resolvedQuestionKeywords,
      ...resolvedIndiaKeywords,
      ...resolvedBrandKeywords,
      ...resolvedAlternateNames,
    ]),
  };
};

